class declaration(_Handle):
    _destroy_fn_name = "ifcopenshell_ifc_declaration_destroy"

    def name(self) -> str:
        s = ifcopenshell_string_t()
        if not _bind().ifcopenshell_ifc_declaration_name(self._h, byref(s)):
            return ""
        return _take_string(s)

    def is_(self, name: str) -> bool:
        v = c_bool(False)
        if not _bind().ifcopenshell_ifc_declaration_is_a(self._h, name.encode("utf-8"), byref(v)):
            return False
        return bool(v.value)

    # Upstream SWIG renames the C++ `is(...)` method to `_is(...)` in Python.
    _is = is_

    # SWIG exposes the method as `is()` but that's a Python keyword; the real
    # SWIG wrapper works because SWIG renames it. Provide both spellings.
    def __getattr__(self, name):
        if name == "is":
            return self.is_
        raise AttributeError(name)

    def as_entity(self) -> Optional["entity"]:
        out = _HandleStructP()
        if not _bind().ifcopenshell_ifc_declaration_as_entity(self._h, byref(out)):
            return None
        return _opt_handle(out, _bind().ifcopenshell_ifc_entity_destroy, entity)

    def as_type_declaration(self) -> Optional["type_declaration"]:
        out = _HandleStructP()
        if not _bind().ifcopenshell_ifc_declaration_as_type_declaration(self._h, byref(out)):
            return None
        return _opt_handle(out, _bind().ifcopenshell_ifc_type_declaration_destroy, type_declaration)

    def as_select_type(self) -> Optional["select_type"]:
        out = _HandleStructP()
        if not _bind().ifcopenshell_ifc_declaration_as_select_type(self._h, byref(out)):
            return None
        return _opt_handle(out, _bind().ifcopenshell_ifc_select_type_destroy, select_type)

