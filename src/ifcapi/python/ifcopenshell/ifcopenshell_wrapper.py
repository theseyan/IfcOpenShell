class _Handle:
    __slots__ = ("_h",)
    _destroy_fn_name: Optional[str] = None

    def __init__(self, h):
        # Accept POINTER(_HandleStruct), c_void_p, int, or None.
        if h is None:
            self._h = _HandleStructP()
        elif isinstance(h, _HandleStructP):
            self._h = h
        elif isinstance(h, c_void_p):
            self._h = ctypes.cast(h, _HandleStructP) if h.value else _HandleStructP()
        elif isinstance(h, int):
            self._h = ctypes.cast(c_void_p(h), _HandleStructP) if h else _HandleStructP()
        else:
            self._h = h

    def __del__(self):
        try:
            h = self._h
        except Exception:
            return
        try:
            if h and self._destroy_fn_name:
                lib = ifcopenshell._get_lib()
                getattr(lib, self._destroy_fn_name)(h)
        except Exception:
            pass

    def __bool__(self) -> bool:
        try:
            return bool(self._h) and bool(self._h.contents.ptr)
        except (ValueError, AttributeError):
            return False

    @property
    def _cppptr(self) -> int:
        try:
            if not self._h:
                return 0
            return self._h.contents.ptr or 0
        except (ValueError, AttributeError):
            return 0

    @property
    def _ptr(self):
        """Return the inner ``IfcParse::*`` C++ pointer as a ``c_void_p``.

        Used by interop with our hand-written ``ifcopenshell_util_*`` C ABI
        (e.g. ``util.attribute.get_primitive_type``) which takes the raw
        C++ pointer directly rather than the autogen handle struct.
        """
        return c_void_p(self._cppptr)

    def __eq__(self, other) -> bool:
        return isinstance(other, _Handle) and self._cppptr == other._cppptr

    def __hash__(self) -> int:
        return self._cppptr or 0


def _opt_handle(out, destroy_fn, ctor):
    """Wrap an out-handle if it has a non-null inner pointer; else free it."""
    if out and out.contents.ptr:
        return ctor(out)
    if out:
        destroy_fn(out)
    return None


