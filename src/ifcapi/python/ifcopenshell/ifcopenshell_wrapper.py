class parameter_type(_Handle):
    _destroy_fn_name = "ifcopenshell_ifc_parameter_type_destroy"

    def as_named_type(self) -> Optional["named_type"]:
        out = _HandleStructP()
        if not _bind().ifcopenshell_ifc_parameter_type_as_named_type(self._h, byref(out)):
            return None
        return _opt_handle(out, _bind().ifcopenshell_ifc_named_type_destroy, named_type)

    def as_simple_type(self) -> Optional["simple_type"]:
        out = _HandleStructP()
        if not _bind().ifcopenshell_ifc_parameter_type_as_simple_type(self._h, byref(out)):
            return None
        return _opt_handle(out, _bind().ifcopenshell_ifc_simple_type_destroy, simple_type)

    def as_aggregation_type(self) -> Optional["aggregation_type"]:
        out = _HandleStructP()
        if not _bind().ifcopenshell_ifc_parameter_type_as_aggregation_type(self._h, byref(out)):
            return None
        return _opt_handle(out, _bind().ifcopenshell_ifc_aggregation_type_destroy, aggregation_type)

    def __repr__(self) -> str:
        for cast in (self.as_named_type, self.as_simple_type, self.as_aggregation_type):
            v = cast()
            if v is not None:
                return repr(v)
        return "<?>"

    __str__ = __repr__


class named_type(parameter_type):
    _destroy_fn_name = "ifcopenshell_ifc_named_type_destroy"

    def declared_type(self) -> Optional["declaration"]:
        out = _HandleStructP()
        if not _bind().ifcopenshell_ifc_named_type_declared_type(self._h, byref(out)):
            return None
        return _wrap_decl(out)

    def __repr__(self) -> str:
        d = self.declared_type()
        return repr(d) if d is not None else "<?>"

    __str__ = __repr__


class simple_type(parameter_type):
    _destroy_fn_name = "ifcopenshell_ifc_simple_type_destroy"

    def declared_type(self) -> str:
        v = c_int32(-1)
        if not _bind().ifcopenshell_ifc_simple_type_declared_type(self._h, byref(v)):
            return ""
        return _SIMPLE_NAMES.get(v.value, "")

    def __repr__(self) -> str:
        return "<%s>" % self.declared_type()

    __str__ = __repr__


class aggregation_type(parameter_type):
    _destroy_fn_name = "ifcopenshell_ifc_aggregation_type_destroy"

    def type_of_aggregation(self) -> int:
        v = c_int32(-1)
        if not _bind().ifcopenshell_ifc_aggregation_type_type_of_aggregation(self._h, byref(v)):
            return -1
        return int(v.value)

    def type_of_aggregation_string(self) -> str:
        return _AGG_NAMES.get(self.type_of_aggregation(), "")

    def bound1(self) -> int:
        v = c_int32(-1)
        if not _bind().ifcopenshell_ifc_aggregation_type_bound1(self._h, byref(v)):
            return -1
        return int(v.value)

    def bound2(self) -> int:
        v = c_int32(-1)
        if not _bind().ifcopenshell_ifc_aggregation_type_bound2(self._h, byref(v)):
            return -1
        return int(v.value)

    def type_of_element(self) -> Optional[parameter_type]:
        out = _HandleStructP()
        if not _bind().ifcopenshell_ifc_aggregation_type_type_of_element(self._h, byref(out)):
            return None
        return _wrap_parameter_type(out)

    def __repr__(self) -> str:
        fmt = lambda i: "?" if i == -1 else str(i)
        return "<%s [%s:%s] of %r>" % (
            self.type_of_aggregation_string(),
            fmt(self.bound1()),
            fmt(self.bound2()),
            self.type_of_element(),
        )

    __str__ = __repr__


