"""SWIG-compatible facade for schema introspection backed by ifcapi C API.

Presents the same object shape as the original
``ifcopenshell.ifcopenshell_wrapper`` SWIG module (attribute, parameter_type,
declaration, entity, type_declaration, select_type, enumeration_type,
named_type, simple_type, aggregation_type, inverse_attribute,
schema_definition).

Internally this module binds to the autogenerated C ABI emitted by
``src/ifcwrap/binding_generator`` (``ifcopenshell_ifc_*`` functions) so that
schema-introspection logic has a single C++ call site (the IfcParse::* layer
reached through the autogen's struct-handle wrappers). Each Python class wraps
a heap-allocated handle struct of the form ``{ void* ptr; bool owned; }`` and
calls the matching ``*_destroy`` function on garbage collection. The
underlying C++ schema objects live for the process lifetime, so destroy here
only frees the small handle wrapper.

For interop with our hand-written ``ifcopenshell_util_*`` C ABI (which still
takes raw ``IfcParse::*`` pointers), the base ``_Handle`` exposes a ``_ptr``
property that returns a ``c_void_p`` pointing at that underlying C++ object
(extracted from the first field of the wrapper struct).

Also provides a couple of stubs (map_shape, function_item_evaluator,
helmert_curve_point, convert_loop_to_function_item) used by alignment
fallbacks that don't have a native geometry backend.
"""

